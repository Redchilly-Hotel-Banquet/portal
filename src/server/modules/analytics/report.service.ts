import { ObjectId } from "mongodb";
import { after } from "next/server";
import { HttpError } from "../../httpError";
import { mongoConnection } from "../../mongo";
import type { AuthenticatedUser } from "../../session";
import { r2 } from "../../storage/r2";
import { paymentModeLabel } from "../../../lib/payment-modes";
import { analyticsService } from "./analytics.service";
import { GUESTS_EXPORT_LIMIT, insightsService, parseWindow } from "./insights.service";
import type { ReportModel } from "./report-model";
import { writeCsv, writePdf, writeXlsx } from "./report-writers";

const COLLECTION = "analytics_reports";
const KINDS = ["branches", "guests", "trends"] as const;
const FORMATS = ["xlsx", "pdf", "csv"] as const;
type Kind = (typeof KINDS)[number];
type Format = (typeof FORMATS)[number];

const CONTENT_TYPES: Record<Format, string> = {
  xlsx: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  pdf: "application/pdf",
  csv: "text/csv; charset=utf-8",
};
const KIND_LABEL: Record<Kind, string> = { branches: "Branches", guests: "Guests", trends: "Trends" };
/** A report still "processing" after this long was lost with its server; show it as failed. */
const STALE_MS = 10 * 60_000;

type ReportRequest = {
  action?: "list" | "list_all" | "create" | "download" | "delete";
  kind?: string;
  format?: string;
  from?: string;
  to?: string;
  outlets?: unknown;
  id?: string;
};

const cleanOutlets = (value: unknown): string[] =>
  Array.from(new Set(Array.isArray(value) ? value.map((key) => String(key).trim()).filter(Boolean) : [])).sort();

/**
 * The branches a report really covers: the ones chosen, kept within what the account may see, or everything it may
 * see when none are chosen ("*" is every branch). Reports are shared by every administrator, so two reports are
 * the same only when they cover the same branches, and a narrower account never sees a broader report's figures.
 */
const coverage = (user: AuthenticatedUser, chosen: string[]): string[] => {
  const all = user.outlets.includes("all");
  if (chosen.length === 0) return all ? ["*"] : [...user.outlets].sort();
  return (all ? chosen : chosen.filter((key) => user.outlets.includes(key))).sort();
};
const filtersKey = (from: string, to: string, covered: string[]) => `${from}|${to}|${covered.join(",")}`;
const col = () => mongoConnection.getDb().collection(COLLECTION);
const objectId = (value: unknown): ObjectId => {
  try {
    return new ObjectId(String(value));
  } catch {
    throw new HttpError(400, "Invalid report id");
  }
};

const present = (doc: any) => {
  const stale = doc.status === "PROCESSING" && Date.now() - new Date(doc.created_at).getTime() > STALE_MS;
  return {
    id: String(doc._id),
    kind: doc.kind,
    format: doc.format,
    status: stale ? "FAILED" : doc.status,
    file_name: doc.file_name,
    size: doc.size ?? null,
    error: stale ? "This report did not finish. Delete it and try again." : (doc.error ?? null),
    created_at: doc.created_at,
    completed_at: doc.completed_at ?? null,
    created_by_name: doc.created_by_name ?? "",
    period_from: doc.filters?.from ?? null,
    period_to: doc.filters?.to ?? null,
    /** Branch keys the report covers; "*" is every branch. */
    branches: Array.isArray(doc.coverage) ? doc.coverage : [],
  };
};

/** Any administrator may open or delete a report, as long as every branch it covers is one they can see. */
const canTouch = (user: AuthenticatedUser, doc: any) =>
  user.outlets.includes("all") ||
  (Array.isArray(doc.coverage) && doc.coverage.length > 0 && doc.coverage.every((key: string) => key !== "*" && user.outlets.includes(key)));

const money = (value: unknown) => Math.round(Number(value ?? 0) * 100) / 100;
const dayLabel = (iso: string) => new Date(`${iso}T00:00:00Z`).toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric", timeZone: "UTC" });

const describe = (kind: Kind, user: AuthenticatedUser, from: string, to: string, outlets: string[], names: Map<string, string>): string[] => {
  const visible = user.outlets.includes("all") ? Array.from(names.keys()) : user.outlets;
  const chosen = outlets.length > 0 ? outlets.filter((key) => visible.includes(key)) : visible;
  const days = Math.round((Date.parse(`${to}T00:00:00Z`) - Date.parse(`${from}T00:00:00Z`)) / 86_400_000) + 1;
  return [
    `Report: ${KIND_LABEL[kind]} analytics`,
    `Period: ${dayLabel(from)} to ${dayLabel(to)} (${days} day${days === 1 ? "" : "s"})`,
    `Branches: ${outlets.length === 0 ? "All branches" : "Selected branches"} (${chosen.length}): ${chosen.map((key) => names.get(key) ?? key).join(", ") || "none"}`,
    `Generated by: ${user.name}${user.email ? ` (${user.email})` : ""}`,
    `Generated on: ${new Date().toLocaleString("en-IN", { timeZone: "Asia/Kolkata" })} (India time)`,
  ];
};

async function buildModel(kind: Kind, user: AuthenticatedUser, from: string, to: string, outlets: string[]): Promise<ReportModel> {
  const db = mongoConnection.getDb();
  const names = new Map<string, string>(
    (await db.collection("outlets").find({}).project({ location_key: 1, name: 1 }).toArray()).map((o: any) => [String(o.location_key), String(o.name ?? o.location_key)]),
  );
  const subtitle = describe(kind, user, from, to, outlets, names);

  if (kind === "trends") {
    const range = parseWindow(from, to)!;
    const data = await insightsService.trends(user, range, outlets);
    return {
      title: "Trends report",
      subtitle,
      sections: [
        {
          title: "Summary",
          columns: [{ header: "Measure", key: "measure" }, { header: "Value", key: "value", kind: "text" }],
          rows: [
            { measure: "Total income", value: `₹${data.totals.income.toLocaleString("en-IN")}` },
            { measure: "Bookings", value: data.totals.bookings },
            { measure: "Room income", value: `₹${data.totals.room_income.toLocaleString("en-IN")}` },
            { measure: "Food orders", value: data.totals.food_orders },
            { measure: "Food income", value: `₹${data.totals.food_income.toLocaleString("en-IN")}` },
          ],
        },
        {
          title: data.unit === "day" ? "By day" : "By month",
          columns: [
            { header: data.unit === "day" ? "Day" : "Month", key: "bucket" },
            { header: "Bookings", key: "bookings", kind: "number" },
            { header: "Room income", key: "room_income", kind: "money" },
            { header: "Food orders", key: "food_orders", kind: "number" },
            { header: "Food income", key: "food_income", kind: "money" },
          ],
          rows: data.series,
        },
        {
          title: "Room types",
          columns: [{ header: "Room type", key: "type" }, { header: "Bookings", key: "bookings", kind: "number" }, { header: "Income", key: "income", kind: "money" }],
          rows: data.room_types,
        },
        {
          title: "Top food items",
          columns: [{ header: "Item", key: "name" }, { header: "Category", key: "category" }, { header: "Sold", key: "quantity", kind: "number" }, { header: "Sales", key: "sales", kind: "money" }],
          rows: data.top_items,
        },
        {
          title: "Food by category",
          columns: [{ header: "Category", key: "category" }, { header: "Sales", key: "sales", kind: "money" }],
          rows: data.food_categories,
        },
        {
          title: "Payments",
          columns: [{ header: "Source", key: "mode" }, { header: "Amount", key: "amount", kind: "money" }],
          rows: data.payments.map((row) => ({ mode: paymentModeLabel(row.mode), amount: row.amount })),
        },
        {
          title: "By branch",
          columns: [
            { header: "Branch", key: "outlet_name" },
            { header: "Bookings", key: "bookings", kind: "number" },
            { header: "Room income", key: "room_income", kind: "money" },
            { header: "Food orders", key: "food_orders", kind: "number" },
            { header: "Food income", key: "food_income", kind: "money" },
          ],
          rows: data.branches,
        },
      ],
    };
  }

  if (kind === "guests") {
    const range = parseWindow(from, to)!;
    const data = await insightsService.guests(user, range, outlets, GUESTS_EXPORT_LIMIT);
    return {
      title: "Guests report",
      subtitle: [...subtitle, `${data.total_guests} guests, ${data.repeat_guests} returning`],
      sections: [
        {
          title: "Guests",
          columns: [
            { header: "Guest", key: "name" },
            { header: "Phone", key: "phone" },
            { header: "Email", key: "email" },
            { header: "Bookings", key: "bookings", kind: "number" },
            { header: "Nights", key: "nights", kind: "number" },
            { header: "Room types", key: "room_types" },
            { header: "Room spend", key: "room_spend", kind: "money" },
            { header: "Food orders", key: "food_orders", kind: "number" },
            { header: "Food spend", key: "food_spend", kind: "money" },
            { header: "Total spend", key: "total_spend", kind: "money" },
            { header: "Paid by", key: "paid_by" },
            { header: "Last booked", key: "last_booked" },
          ],
          rows: data.guests.map((guest) => ({
            name: guest.name,
            phone: guest.phone,
            email: guest.email,
            bookings: guest.bookings,
            nights: guest.nights,
            room_types: Object.entries(guest.room_types).map(([type, count]) => `${type} x${count}`).join(", "),
            room_spend: guest.room_spend,
            food_orders: guest.food_orders,
            food_spend: guest.food_spend,
            total_spend: guest.total_spend,
            paid_by: Object.entries(guest.payments).map(([mode, amount]) => `${paymentModeLabel(mode)} ${amount}`).join(", "),
            last_booked: guest.last_booking ? new Date(guest.last_booking as any).toLocaleDateString("en-IN", { timeZone: "Asia/Kolkata" }) : "",
          })),
        },
      ],
    };
  }

  const data = await analyticsService.getOutletAnalytics(user, { from, to });
  const rows = data.outlets.filter((o) => outlets.length === 0 || outlets.includes(o.outlet_id));
  const sum = (pick: (o: (typeof rows)[number]) => number) => rows.reduce((total, o) => total + pick(o), 0);
  const payments = new Map<string, number>();
  for (const o of rows) for (const [mode, amount] of Object.entries(o.payments_by_mode ?? {})) payments.set(mode, (payments.get(mode) ?? 0) + Number(amount));
  return {
    title: "Branches report",
    subtitle,
    sections: [
      {
        title: "Branch figures",
        columns: [
          { header: "Branch", key: "outlet_name" },
          { header: "Orders", key: "total_orders", kind: "number" },
          { header: "Revenue", key: "total_revenue", kind: "money" },
          { header: "Food", key: "food_revenue", kind: "money" },
          { header: "Rooms", key: "room_revenue", kind: "money" },
          { header: "Bookings", key: "total_bookings", kind: "number" },
          { header: "Active bookings", key: "active_bookings", kind: "number" },
          { header: "Rooms (count)", key: "total_rooms", kind: "number" },
          { header: "Tables", key: "total_tables", kind: "number" },
          { header: "Orders today", key: "today_orders", kind: "number" },
          { header: "GST collected", key: "gst_collected", kind: "money" },
        ],
        rows: [
          ...rows.map((o) => ({
            outlet_name: o.outlet_name,
            total_orders: o.total_orders,
            total_revenue: money(o.total_revenue),
            food_revenue: money(o.food_revenue),
            room_revenue: money(Math.max(0, o.total_revenue - o.food_revenue)),
            total_bookings: o.total_bookings,
            active_bookings: o.active_bookings,
            total_rooms: o.total_rooms,
            total_tables: o.total_tables,
            today_orders: o.today_orders,
            gst_collected: money(o.gst_collected),
          })),
          {
            outlet_name: "Total",
            total_orders: sum((o) => o.total_orders),
            total_revenue: money(sum((o) => o.total_revenue)),
            food_revenue: money(sum((o) => o.food_revenue)),
            room_revenue: money(sum((o) => Math.max(0, o.total_revenue - o.food_revenue))),
            total_bookings: sum((o) => o.total_bookings),
            active_bookings: sum((o) => o.active_bookings),
            total_rooms: sum((o) => o.total_rooms),
            total_tables: sum((o) => o.total_tables),
            today_orders: sum((o) => o.today_orders),
            gst_collected: money(sum((o) => o.gst_collected)),
          },
        ],
      },
      {
        title: "Payments by source",
        columns: [{ header: "Source", key: "mode" }, { header: "Amount", key: "amount", kind: "money" }],
        rows: Array.from(payments, ([mode, amount]) => ({ mode: paymentModeLabel(mode), amount: money(amount) })),
      },
    ],
  };
}

const generate = async (id: ObjectId, kind: Kind, format: Format, user: AuthenticatedUser, from: string, to: string, outlets: string[]) => {
  try {
    const model = await buildModel(kind, user, from, to, outlets);
    const bytes = format === "xlsx" ? await writeXlsx(model) : format === "pdf" ? await writePdf(model) : writeCsv(model);
    const day = new Date(Date.now() + 5.5 * 3_600_000).toISOString().slice(0, 10);
    const key = `Reports/${day}/${id}.${format}`;
    await r2.put(key, bytes, CONTENT_TYPES[format]);
    await col().updateOne({ _id: id }, { $set: { status: "READY", r2_key: key, size: bytes.length, completed_at: new Date() } });
  } catch (error) {
    console.error("[reports] generation failed", error);
    await col().updateOne({ _id: id }, { $set: { status: "FAILED", error: error instanceof HttpError ? error.message : "The report could not be generated.", completed_at: new Date() } });
  }
};

export const reportService = {
  async handle(request: ReportRequest, user: AuthenticatedUser) {
    if (!user.roles.includes("admin")) throw new HttpError(403, "Insufficient permissions to manage reports");

    switch (request?.action) {
      case "create": {
        const kind = request.kind as Kind;
        const format = request.format as Format;
        if (!KINDS.includes(kind)) throw new HttpError(400, "Unknown report");
        if (!FORMATS.includes(format)) throw new HttpError(400, "Choose Excel, PDF or CSV");
        const from = String(request.from ?? "");
        const to = String(request.to ?? "");
        // The same checks as the screen: valid days, at most a year (the branch view keeps its six months).
        const window = parseWindow(from, to)!;
        if (kind === "branches" && window.days > 184) throw new HttpError(400, "The branch report covers at most 6 months.");
        const outlets = cleanOutlets(request.outlets);
        const covered = coverage(user, outlets);
        if (covered.length === 0) throw new HttpError(403, "You do not have access to those branches.");
        const names = `${kind}-${from}-to-${to}`;
        const doc = {
          kind,
          format,
          filters: { from, to, outlets },
          filters_key: filtersKey(from, to, covered),
          coverage: covered,
          status: "PROCESSING",
          file_name: `${names}.${format}`,
          created_by: user.id,
          created_by_name: user.name,
          created_at: new Date(),
        };
        const { insertedId } = await col().insertOne(doc as any);
        // Runs after the response is sent, so the page is not held up while the file is built and stored.
        after(() => generate(insertedId, kind, format, user, from, to, outlets));
        return { report: present({ ...doc, _id: insertedId }) };
      }

      case "download": {
        const doc = await col().findOne({ _id: objectId(request.id) });
        if (!doc || !canTouch(user, doc)) throw new HttpError(404, "Report not found");
        if (doc.status !== "READY" || !doc.r2_key) throw new HttpError(409, "This report is not ready.");
        const bytes = await r2.getBytes(doc.r2_key);
        if (!bytes) throw new HttpError(404, "The file is no longer in storage. Delete this report and generate it again.");
        return { file_name: doc.file_name, content_type: CONTENT_TYPES[doc.format as Format], data: bytes.toString("base64") };
      }

      case "delete": {
        const doc = await col().findOne({ _id: objectId(request.id) });
        if (!doc || !canTouch(user, doc)) throw new HttpError(404, "Report not found");
        if (doc.status === "PROCESSING" && Date.now() - new Date(doc.created_at).getTime() <= STALE_MS) {
          throw new HttpError(409, "This report is still being generated. Delete it once it finishes.");
        }
        // The file first: if the bucket refuses, the row stays so the report can be tried again.
        if (doc.r2_key) await r2.remove(doc.r2_key);
        await col().deleteOne({ _id: doc._id });
        return { ok: true };
      }

      case "list_all": {
        // Every report this account may open, newest first, whatever its kind, period or branches.
        const scope = user.outlets.includes("all")
          ? {}
          : { "coverage.0": { $exists: true }, coverage: { $not: { $elemMatch: { $nin: user.outlets } } } };
        const docs = await col().find(scope).sort({ created_at: -1 }).limit(200).toArray();
        return { reports: docs.map(present) };
      }

      default: {
        const kind = request?.kind as Kind;
        if (!KINDS.includes(kind)) throw new HttpError(400, "Unknown report");
        const covered = coverage(user, cleanOutlets(request.outlets));
        const docs = await col()
          .find({ kind, filters_key: filtersKey(String(request.from ?? ""), String(request.to ?? ""), covered) })
          .sort({ created_at: -1 })
          .limit(50)
          .toArray();
        return { reports: docs.map(present), label: KIND_LABEL[kind] };
      }
    }
  },
};
